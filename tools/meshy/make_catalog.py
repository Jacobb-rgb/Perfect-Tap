"""Writes src/shared/Config/MeshCatalog.luau from a processing manifest (tools/meshy/process_glb.py).

python3 -I tools/meshy/make_catalog.py tools/meshy/manifest_2026-11-13.json src/shared/Config/MeshCatalog.luau [spots.json]
(spots.json from tools/meshy/surface_spots.py: Surface = Tint + Spots per mesh)
"""
import json, re, sys

src, out = sys.argv[1], sys.argv[2]
m = json.load(open(src))
spots = json.load(open(sys.argv[3])) if len(sys.argv) > 3 else {}
parts = sorted((p for v in m.values() for p in v["parts"]), key=lambda p: p["name"])

def v3(a):
    return "Vector3.new(%s)" % ", ".join(repr(round(x, 4)) for x in a)

floors, floors_hd, floors_next, ores, rocks, props = {}, {}, {}, [], [], []
# a floor's newest set, re-processed from the owner's diorama with different cuts (2026-11-17: the
# quarry whole, only the DEPTHS walk-through cut: Floor_QuarryCHD_*): a floor takes it first
NEXT = {"QuarryC": "Quarry"}
for p in parts:
    n = p["name"]
    t = re.match(r"^Floor_([A-Za-z]+)_(\d+)$", n)
    if t:
        # a re-cut diorama keeps its floor: Floor_QuarryB_* are the Quarry's tiles; Floor_<Id>HD_*
        # the same diorama re-processed sharper (2026-11-14: more triangles, baked normal maps)
        fid = t.group(1)
        hd = fid.endswith("HD")
        if hd:
            fid = fid[:-2]
        if hd and fid in NEXT:
            floors_next.setdefault(NEXT[fid], []).append(n)
            continue
        fid = {"QuarryB": "Quarry"}.get(fid, fid)
        (floors_hd if hd else floors).setdefault(fid, []).append(n)
    elif n.startswith("Ore_") and not n.endswith("_Low"):
        ores.append(n[4:])
    elif n.startswith("Rock_"):
        rocks.append(n[5:])
    elif n.startswith("Prop_"):
        props.append(n[5:])

L = []
L.append("--!strict")
L.append("--[[")
L.append("\tGenerated by tools/meshy/make_catalog.py from " + src.split("/")[-1] + " (do not edit by hand).")
L.append("\tThe owner's 3D models (Meshy, 2026-11-13) as processed for Roblox (docs/plans/MESHY_MODELS_PLAN.md):")
L.append("\tone entry per MeshPart the owner uploads. Box = its size in the processed file (studs at import),")
L.append("\tCenter = its centre there (floor tiles: where the tile sits in its diorama), Tris = triangles.")
L.append("]]")
L.append("")
L.append("export type Entry = { Box: Vector3, Center: Vector3, Tris: number }")
L.append("")
L.append("local MeshCatalog = {}")
L.append("")
L.append("MeshCatalog.Assets = {")
for p in parts:
    L.append('\t%s = { Box = %s, Center = %s, Tris = %d },' % (p["name"], v3(p["size"]), v3(p["center"]), p["tris"]))
L.append("} :: { [string]: Entry }")
L.append("")
L.append("-- Ore ids with a model (Ore_<Id> for displays, Ore_<Id>_Low for crowds).")
L.append("MeshCatalog.Ores = {")
for o in ores:
    L.append("\t%s = true," % o)
L.append("} :: { [string]: boolean }")
L.append("")
L.append("-- Rock models: Rock_<FloorId>_<Kind>.")
L.append("MeshCatalog.Rocks = {")
for r in rocks:
    L.append('\t%s = true,' % r)
L.append("} :: { [string]: boolean }")
L.append("")
L.append("-- Props: Prop_<Name>.")
L.append("MeshCatalog.Props = {")
for r in props:
    L.append('\t%s = true,' % r)
L.append("} :: { [string]: boolean }")
L.append("")
L.append("-- Surface of a mesh: Tint = its average colour, Spots = upper/outer surface points as fractions")
L.append("-- of its box from the box centre (P, -0.5..0.5 per axis) with the outward normal N (glints, cracks).")
L.append("export type Spot = { P: Vector3, N: Vector3 }")
L.append("MeshCatalog.Surface = {")
for name in sorted(spots):
    e = spots[name]
    t = e["tint"]
    L.append("\t%s = {" % name)
    L.append("\t\tTint = Color3.new(%s, %s, %s)," % (repr(round(t[0], 3)), repr(round(t[1], 3)), repr(round(t[2], 3))))
    L.append("\t\tSpots = {")
    for sp in e["spots"]:
        L.append("\t\t\t{ P = %s, N = %s }," % (v3(sp[0:3]), v3(sp[3:6])))
    L.append("\t\t},")
    L.append("\t},")
L.append("} :: { [string]: { Tint: Color3, Spots: { Spot } } }")
L.append("")
L.append("-- Floor dioramas: their tiles (Floor_<FloorId>_<NN>), in order.")
L.append("MeshCatalog.Floors = {")
for f in sorted(floors):
    L.append("\t%s = {" % f)
    for n in floors[f]:
        L.append('\t\t"%s",' % n)
    L.append("\t},")
L.append("} :: { [string]: { string } }")
L.append("")
L.append("-- The same dioramas re-processed sharper (Floor_<FloorId>HD_<NN>): a floor takes these once")
L.append("-- every one is uploaded (MineFloors.floorTiles).")
L.append("MeshCatalog.FloorsHD = {")
for f in sorted(floors_hd):
    L.append("\t%s = {" % f)
    for n in floors_hd[f]:
        L.append('\t\t"%s",' % n)
    L.append("\t},")
L.append("} :: { [string]: { string } }")
L.append("")
L.append("-- A floor's newest set, its diorama re-processed with different cuts (the quarry whole, only the")
L.append("-- DEPTHS walk-through, 2026-11-17): a floor takes it first, once every tile is uploaded, with its own")
L.append("-- walk data (DioramaData.<FloorId>Next).")
L.append("MeshCatalog.FloorsNext = {")
for f in sorted(floors_next):
    L.append("\t%s = {" % f)
    for n in floors_next[f]:
        L.append('\t\t"%s",' % n)
    L.append("\t},")
L.append("} :: { [string]: { string } }")
L.append("")
L.append("return MeshCatalog")
open(out, "w").write("\n".join(L) + "\n")
print("wrote", out, len(parts), "assets", len(ores), "ores", len(rocks), "rocks", len(props), "props", {k: len(v) for k, v in floors.items()}, "HD", {k: len(v) for k, v in floors_hd.items()}, "next", {k: len(v) for k, v in floors_next.items()})
